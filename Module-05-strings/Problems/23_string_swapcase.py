# Variable
text = "pyTHON PROGRAMMing"
# Original Result
print(f"Text : {text}")
# Formula 1(swapping to uppercase)
uppercase_text = text.upper()
# Heading uppercase
print("-" * 40)
print("Uppercase Method".center(40))
print("-" * 40)
# Display Results
print(f"Text           : {text}")
print(f"Uppercase Text : {uppercase_text}")
print()
# Formula 2(swapping to lowercase)
lower_text = text.lower()
# Heading lowercase
print("-" * 40)
print("Lowercase Method".center(40))
print("-" * 40)
# Display Results
print(f"Text           : {text}")
print(f"Lowercase Text : {lower_text}")
print()
# Formula 3(swappcase)
swap_text = text.swapcase()
# Heading swapcase
print("-" * 40)
print("Swapcase Method".center(40))
print("-" * 40)
# Display Results
print(f"Text           : {text}")
print(f"Swapcase Text : {swap_text}")
print()
